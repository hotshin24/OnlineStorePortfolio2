import re as _re
PH = _re.compile(r'\{([A-Z_]+)\.([A-Z_]+)\}')

def check(valid_cols, codes):
    """자리표시자 컬럼과 코드 값이 실제로 있는지 검사."""
    bad = []
    for g, d in REL.items():
        if g not in codes: bad.append(('group', g)); continue
        known = {v[0] for v in codes[g]}
        for c, items in d.items():
            if c not in known: bad.append(('code', g, c))
            for x in items:
                for t, col in PH.findall(x):
                    if (t, col) not in valid_cols: bad.append(('col', t, col))
    assert not bad, bad

def items(group, code, fmt):
    """fmt(table, col) -> 참조 문자열(백틱 포함 가능)."""
    return [PH.sub(lambda m: fmt(m.group(1), m.group(2)), x) for x in REL.get(group, {}).get(code, [])]
