def il(s):
    s = html.escape(str(s)); p = s.split('`')
    s = ''.join(f'<code>{x}</code>' if i % 2 else x for i, x in enumerate(p))
    return re.sub(r'\[(확인 필요[^\]]*)\]', r'<span class="warn">[\1]</span>', s)

def table(head, rows, widths=None):
    cg = ''.join(f'<col style="width:{w}">' for w in widths) if widths else ''
    h = ''.join(f'<th>{il(x)}</th>' for x in head)
    b = ''.join('<tr>' + ''.join(f'<td>{il(c)}</td>' for c in r) + '</tr>' for r in rows)
    return f'<table style="table-layout:fixed"><colgroup>{cg}</colgroup><tr>{h}</tr>{b}</table>'

