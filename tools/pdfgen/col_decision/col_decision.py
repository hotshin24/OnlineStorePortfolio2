def il(s):
    s = html.escape(s); p = s.split('`')
    s = ''.join(f'<code>{x}</code>' if i % 2 else x for i, x in enumerate(p))
    s = re.sub(r'\*\*(.+?)\*\*', r'<b>\1</b>', s)
    return s.replace('[변경]', '<span class="chg">[변경]</span>')

def ul(items):
    return '<ul>' + ''.join(f'<li>{il(x)}</li>' for x in items) + '</ul>'

